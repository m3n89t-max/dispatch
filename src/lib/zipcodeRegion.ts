/**
 * 우편번호(+선택적 주소)로 배차 구역 판정
 * @param zipcode '63xxx' 형식 5자리 우편번호
 * @param address 주소 텍스트 (선택 - 중복 우편번호 보조 판정용)
 * @returns 'A' | 'B' | 'C' | 'D' | 'E' | 'UNKNOWN'
 */
export function getRegionByZipcode(zipcode: string | null | undefined, address?: string | null): RegionCode {
  const z = (zipcode ?? '').toString().trim()
  if (!z) return address ? getRegionByAddress(address) : 'UNKNOWN'

  // 중복 우편번호 → 주소로 재판정
  if (DUAL_REGION_AB.has(z)) {
    if (address) {
      if (B_KEYWORDS.test(address)) return 'B'
      if (A_KEYWORDS.test(address)) return 'A'
    }
    return 'UNKNOWN' // 주소 정보 없으면 수동 보정 대상
  }

  if (A구역.has(z)) return 'A'
  if (B구역.has(z)) return 'B'
  if (C구역.has(z)) return 'C'
  if (D구역.has(z)) return 'D'
  if (E구역.has(z)) return 'E'

  // 우편번호로 못 찾으면 주소 텍스트 fallback
  return address ? getRegionByAddress(address) : 'UNKNOWN'
}

/**
 * 주소 텍스트만으로 배차 구역 판정 (우편번호 없을 때 fallback)
 */
export function getRegionByAddress(address: string | null | undefined): RegionCode {
  const a = (address ?? '').toString()
  if (!a) return 'UNKNOWN'

  // 동·읍·면 키워드 매칭 (특이도 높은 순서로)
  if (D_KEYWORDS.test(a)) return 'D'
  if (E_KEYWORDS.test(a)) return 'E'
  if (C_KEYWORDS.test(a)) return 'C'
  if (B_KEYWORDS.test(a)) return 'B'
  if (A_KEYWORDS.test(a)) return 'A'

  return 'UNKNOWN'
}

