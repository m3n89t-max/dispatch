/**
 * 최후 보정: 동 키워드도 없고 카카오 지오코딩도 실패한 주소를 시(市) 단위로 배정.
 * (예: "제주특별자치도 제주시 과원북2길 12 (부영아파트) 5차 505동 1003호" — 도로명만 있고 지오코딩 실패)
 * 미분류로 남으면 자동배차에서 누락되므로, 최소한 시 단위로는 배차 가능하게 한다.
 *  - 읍·면이 들어있으면 D/E 가 이미 판정되므로 여기 오지 않음
 *  - 서귀포시 → C(서귀포) / 제주시 → A(구제주, 신제주는 연동·노형 등 키워드로 이미 B 판정)
 */
export function getRegionByCity(address: string | null | undefined): RegionCode {
  const a = (address ?? '').toString()
  if (!a) return 'UNKNOWN'
  if (a.includes('서귀포시')) return 'C'
  if (a.includes('제주시')) return 'A'
  return 'UNKNOWN'
}

/** 카카오 region_3depth_name(동/읍/면)으로 구역 판정. 못 찾으면 UNKNOWN. */
export function getRegionByDong(dong: string | null | undefined): RegionCode {
  const d = (dong ?? '').toString().replace(/\s/g, '')
  if (!d) return 'UNKNOWN'
  for (const [region, bases] of DONG_REGION) {
    for (const b of bases) if (d.startsWith(b)) return region
  }
  return 'UNKNOWN'
}
